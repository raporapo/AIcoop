import { describe, expect, it } from "vitest";
import { isBlockedAddress } from "./address.ts";

// 箱から内部アドレスへは届かない（5.1.4、docs/development.md の未決 #2）。
// Gondolin の既定の判定（ループバック・プライベート・リンクローカルなど）に、
// 抜けている範囲を足して拒否側に倒す。
describe("5.1.4：内部アドレスへの接続を塞ぐ isBlockedAddress", () => {
  it.each([
    ["0.0.0.0", "この網"],
    ["10.1.2.3", "プライベート"],
    ["100.64.0.1", "CGNAT"],
    ["127.0.0.1", "ループバック"],
    ["127.255.255.254", "ループバック"],
    ["169.254.169.254", "クラウドのメタデータ（リンクローカル）"],
    ["172.16.0.1", "プライベート"],
    ["172.31.255.255", "プライベート"],
    ["192.0.0.1", "IETF の予約"],
    ["192.0.2.1", "文書用"],
    ["192.168.127.1", "Gondolin のゲートウェイ"],
    ["198.18.0.1", "ベンチマーク用（Gondolin の合成DNSの範囲）"],
    ["198.51.100.7", "文書用"],
    ["203.0.113.9", "文書用"],
    ["224.0.0.251", "マルチキャスト"],
    ["240.0.0.1", "予約"],
    ["255.255.255.255", "ブロードキャスト"],
  ])("IPv4 %s（%s）は塞ぐ", (ip) => {
    expect(isBlockedAddress(ip)).toBe(true);
  });

  it.each([
    ["::", "未指定"],
    ["::1", "ループバック"],
    ["::ffff:127.0.0.1", "IPv4 射影のループバック"],
    ["::ffff:169.254.169.254", "IPv4 射影のメタデータ"],
    ["::127.0.0.1", "IPv4 互換（廃止）"],
    ["64:ff9b::7f00:1", "NAT64 で 127.0.0.1"],
    ["64:ff9b::a00:1", "NAT64 で 10.0.0.1"],
    ["64:ff9b:1::1", "NAT64 のローカル用"],
    ["2002:7f00:1::1", "6to4 で 127.0.0.1"],
    ["2001::1", "Teredo"],
    ["2001:db8::1", "文書用"],
    ["100::1", "破棄用"],
    ["fc00::1", "ULA"],
    ["fd12:3456::1", "ULA"],
    ["fe80::1", "リンクローカル"],
    ["fec0::1", "サイトローカル（廃止）"],
    ["ff02::1", "マルチキャスト"],
  ])("IPv6 %s（%s）は塞ぐ", (ip) => {
    expect(isBlockedAddress(ip)).toBe(true);
  });

  it.each(["", "localhost", "example.com", "1.2.3", "999.1.1.1", "::g"])(
    "IP アドレスとして読めない %j は塞ぐ（拒否側に倒す）",
    (ip) => {
      expect(isBlockedAddress(ip)).toBe(true);
    },
  );

  it.each([
    "8.8.8.8",
    "1.1.1.1",
    "140.82.112.3",
    "172.15.255.255",
    "172.32.0.1",
    "100.63.255.255",
    "2606:4700::6810:84e5",
    "2a00:1450:4001:82a::200e",
    "64:ff9b::808:808",
    "2002:808:808::1",
  ])("公開のアドレス %s は塞がない", (ip) => {
    expect(isBlockedAddress(ip)).toBe(false);
  });
});
